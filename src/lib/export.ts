import type { HealthRecord, Summary } from "@/types";

/** Download a text file from the browser. No data leaves the device. */
export function downloadText(filename: string, text: string, mime: string): void {
  const blob = new Blob([text], { type: mime });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  URL.revokeObjectURL(url);
}

export function summaryToMarkdown(record: HealthRecord, summary: Summary): string {
  const lines: string[] = [
    `# AI Summary — ${record.title}`,
    "",
    `Document type: ${record.type}`,
    `Generated by: AI Health Records Assistant (rule-based summary, not a diagnosis)`,
    "",
    "## Plain-English Summary",
    "",
    ...summary.summary.map((s) => `${s}`),
    "",
    "## Key Findings",
    "",
    ...(summary.keyFindings.length > 0
      ? summary.keyFindings.map((f) => `- ${f}`)
      : ["- No key findings extracted."]),
    "",
    "## Follow-up Checklist",
    "",
    ...(summary.followUps.length > 0
      ? summary.followUps.map((f) => `- [ ] ${f}`)
      : ["- [ ] Review this summary with your clinician."]),
    "",
    "## Questions to Ask Your Doctor",
    "",
    ...(summary.questions.length > 0
      ? summary.questions.map((q) => `- ${q}`)
      : ["- Is there anything in this document I should be concerned about?"]),
    "",
    "---",
    "",
    "Disclaimer: This summary was generated by deterministic rules from the",
    "document text. It is not medical advice and is not a diagnosis. Do not",
    "upload real personal health information to this demo.",
  ];
  return lines.join("\n");
}

export function recordsToJson(records: HealthRecord[]): string {
  return JSON.stringify({ exportedAt: new Date().toISOString(), records }, null, 2);
}
